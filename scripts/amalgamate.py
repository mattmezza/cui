#!/usr/bin/env python3
"""Reproduce standalone distribution headers; no network/toolchain required."""
import argparse,difflib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
MODULES=json.loads((ROOT/"cmake/sources.json").read_text(encoding="utf-8"))["modules"]
def generate(name,sources):
    declaration=(ROOT/"include/cui"/(name+".h")).read_text(encoding="utf-8")
    declaration=re.sub(r'#include "cui/([^"\n]+)"',r'#include "\1"',declaration)
    # Mark completion inside the declaration guard: recursive includes must not
    # emit implementation while a dependency is still declaring its types.
    ready = name.upper() + '_DECLARATIONS_READY'
    end = declaration.rfind('#endif')
    assert end >= 0, name
    declaration = declaration[:end] + f'#define {ready}\n' + declaration[end:]
    lines=['/* Generated by scripts/amalgamate.py; DO NOT EDIT. SPDX-License-Identifier: MIT */',declaration]
    macro=name.upper()+"_IMPLEMENTATION"
    lines += [f'#if defined({macro}) && defined({ready}) && !defined({macro}_ONCE)',f'#define {macro}_ONCE']
    if name in {"cui_choice", "cui_surface", "cui_form", "cui_status", "cui_message", "cui_text_view", "cui_questionnaire", "cui_virtual_scroll", "cui_editor"}:
        lines += ['#include "cui_components.h"']
    if name == "cui_base":
        lines += ['#include "cui_slider_events.h"', '#include "cui_text_input_events.h"']
    if name == "cui_textarea":
        lines += ['#include "cui_multiline_events.h"']
    if name == "cui_editor":
        lines += ['#include "cui_editor_events.h"']
    if name == "cui_table":
        lines += ['#include "cui_table_events.h"']
    if name == "cui_command":
        lines += ['#include "cui_command_events.h"']
    if name == "cui_toolbar":
        lines += ['#include "cui_toolbar_events.h"']
    if name == "cui_form":
        lines += ['#include "cui_form_events.h"']
    if name == "cui_media":
        lines += ['#include "cui_media_events.h"']
    if name == "cui_settings":
        lines += ['#include "cui_settings_events.h"']
    if name == "cui_tree":
        lines += ['#include "cui_tree_events.h"']
    if name == "cui_disclosure":
        lines += ['#include "cui_disclosure_events.h"']
    if name == "cui_choice":
        lines += ['#include "cui_list_events.h"']
        lines += ['#ifndef CUI_TABS_EVENTS_IMPLEMENTATION', '#define CUI_TABS_EVENTS_IMPLEMENTATION', '#endif', '#include "cui_tabs_events.h"']
    if name == "cui_tabs_events":
        lines += ['#ifndef CUI_CHOICE_IMPLEMENTATION', '#define CUI_CHOICE_IMPLEMENTATION', '#endif', '#include "cui_choice.h"']
    if name == "cui_picker_events":
        lines += ['#include "cui_components.h"', '#ifndef CUI_PICKER_IMPLEMENTATION', '#define CUI_PICKER_IMPLEMENTATION', '#endif', '#include "cui_picker.h"']
    if name == "cui_otp":
        lines += ['#ifndef CUI_OTP_EVENTS_IMPLEMENTATION', '#define CUI_OTP_EVENTS_IMPLEMENTATION', '#endif', '#include "cui_otp_events.h"']
    if name == "cui_otp_events":
        lines += ['#include "cui_components.h"', '#ifndef CUI_OTP_IMPLEMENTATION', '#define CUI_OTP_IMPLEMENTATION', '#endif', '#include "cui_otp.h"']
    if name == "cui_numeric":
        lines += ['#ifndef CUI_NUMERIC_SELECTION_EVENTS_IMPLEMENTATION', '#define CUI_NUMERIC_SELECTION_EVENTS_IMPLEMENTATION', '#endif', '#include "cui_numeric_selection_events.h"']
        lines += ['#ifndef CUI_NUMBER_EVENTS_IMPLEMENTATION', '#define CUI_NUMBER_EVENTS_IMPLEMENTATION', '#endif', '#include "cui_number_events.h"']
    if name in {"cui_number_events", "cui_numeric_selection_events"}:
        lines += ['#include "cui_components.h"']
        lines += ['#ifndef CUI_NUMERIC_IMPLEMENTATION', '#define CUI_NUMERIC_IMPLEMENTATION', '#endif', '#include "cui_numeric.h"']
    if name == "cui_styled_slider_events":
        lines += ['#ifndef CUI_BASE_IMPLEMENTATION', '#define CUI_BASE_IMPLEMENTATION', '#endif', '#include "cui_base.h"']
    if name == "cui_surface_events":
        lines += ['#ifndef CUI_SURFACE_IMPLEMENTATION', '#define CUI_SURFACE_IMPLEMENTATION', '#endif', '#include "cui_surface.h"']
    if name == "cui_video_controls":
        for module in ["cui_components", "cui_video"]:
            lines += [f'#ifndef {module.upper()}_IMPLEMENTATION', f'#define {module.upper()}_IMPLEMENTATION', '#endif', f'#include "{module}.h"']
    if name == "cui_plot_view":
        lines += ['#ifndef CUI_PLOT_IMPLEMENTATION', '#define CUI_PLOT_IMPLEMENTATION', '#endif', '#include "cui_plot.h"']
    if name == "cui_plot_motion":
        for module in ["cui_theme", "cui_plot"]:
            lines += [f'#ifndef {module.upper()}_IMPLEMENTATION', f'#define {module.upper()}_IMPLEMENTATION', '#endif', f'#include "{module}.h"']
    if name in {"cui_chart", "cui_plot_view"}:
        lines += ['#ifndef CUI_PLOT_MOTION_IMPLEMENTATION', '#define CUI_PLOT_MOTION_IMPLEMENTATION', '#endif', '#include "cui_plot_motion.h"']
    if name == "cui_dock":
        lines += ['#if !defined(CUI_DOCK_BASE_ONLY)', '#include "cui_components.h"',
                  '#include "cui_resizable.h"', '#endif']
    if name=="cui_chrome":
        lines += ['#ifndef CUI_ICON_IMPLEMENTATION','#define CUI_ICON_IMPLEMENTATION','#endif','#include "cui_icon.h"']
    if name in {"cui_base", "cui_textarea", "cui_text_overflow"}:
        lines += ['#ifndef CUI_EDIT_IMPLEMENTATION','#define CUI_EDIT_IMPLEMENTATION','#endif','#include "cui_edit.h"']
    if name in {"cui_components", "cui_theme_registry"}:
        lines += ['#ifndef CUI_THEME_IMPLEMENTATION','#define CUI_THEME_IMPLEMENTATION','#endif','#include "cui_theme.h"']
    if name=="cui_components":
        for module in ["cui_boolean_events", "cui_text_overflow", "cui_overlay", "cui_virtual", "cui_plot_motion", "cui_content", "cui_disclosure", "cui_choice", "cui_numeric", "cui_picker", "cui_tree", "cui_table", "cui_scroll", "cui_surface", "cui_form", "cui_otp", "cui_status", "cui_message", "cui_media", "cui_description", "cui_chrome", "cui_resizable", "cui_icon", "cui_toolbar", "cui_sidebar", "cui_textarea", "cui_settings", "cui_carousel", "cui_command", "cui_root", "cui_text_view", "cui_chart", "cui_speech", "cui_questionnaire", "cui_editor", "cui_virtual_scroll", "cui_plot_view", "cui_radio_group", "cui_button_group"]:
            macro_dependency = module.upper()+"_IMPLEMENTATION"
            lines += [f'#ifndef {macro_dependency}',f'#define {macro_dependency}', '#endif',f'#include "{module}.h"']
    for source in sources:
        code=(ROOT/source).read_text(encoding="utf-8")
        code=code.replace('#include "cui_unicode_grapheme.h"', (ROOT/'src/core/cui_unicode_grapheme.h').read_text(encoding='utf-8'))
        for private_include in ['#include "cui_drop_shadow_bounds_internal.h"', '#include "../core/cui_drop_shadow_bounds_internal.h"']:
            code=code.replace(private_include, (ROOT/'src/core/cui_drop_shadow_bounds_internal.h').read_text(encoding='utf-8'))
        code=code.replace('#include "cui_text_paint_internal.h"', (ROOT/'src/core/cui_text_paint_internal.h').read_text(encoding='utf-8'))
        for private_include in ['#include "cui_design_metrics.h"', '#include "../base/cui_design_metrics.h"']:
            code=code.replace(private_include, (ROOT/'src/base/cui_design_metrics.h').read_text(encoding='utf-8'))
        for private_include in ['#include "cui_icon_layout.h"', '#include "../base/cui_icon_layout.h"']:
            code=code.replace(private_include, (ROOT/'src/base/cui_icon_layout.h').read_text(encoding='utf-8'))
        for private_include in ['#include "cui_textarea_geometry.h"', '#include "../base/cui_textarea_geometry.h"']:
            code=code.replace(private_include, (ROOT/'src/base/cui_textarea_geometry.h').read_text(encoding='utf-8'))
        for private_path in ['src/base/cui_form_private.h', 'src/components/cui_input_private.h', 'src/base/cui_command_events_private.h']:
            private_name = private_path.rsplit("/", 1)[-1]
            for private_include in [f'#include "{private_name}"', f'#include "../base/{private_name}"', f'#include "../components/{private_name}"']:
                code = code.replace(private_include, (ROOT/private_path).read_text(encoding='utf-8'))
        if name=='cui_theme_registry':
            for private_name in ['cui_theme_json.h', 'cui_theme_equal.h', 'cui_theme_palette.inc', 'cui_theme_legacy_fields.inc']:
                code=code.replace(f'#include "{private_name}"', (ROOT/'src/theme'/private_name).read_text(encoding='utf-8'))
        if name=='cui_theme':
            code=code.replace('#include "cui_theme_presets.inc"',(ROOT/'src/theme/cui_theme_presets.inc').read_text(encoding='utf-8'))
        if name=='cui_icon':
            for vendor in ['nanosvg.h', 'nanosvgrast.h']:
                code=code.replace(f'#include "../../third_party/nanosvg/{vendor}"',(ROOT/'third_party/nanosvg'/vendor).read_text(encoding="utf-8"))
            code=code.replace('#include "nanosvg.h"', '')
            code=code.replace('#include "cui_icon_assets.inc"',(ROOT/'src/base/cui_icon_assets.inc').read_text(encoding="utf-8"))
        if name=='cui':
            code=code.replace('#include "clay.h"',(ROOT/'third_party/clay/clay.h').read_text(encoding="utf-8"))
        code=re.sub(r'^#include "(?:cui/)?(?:cui[^"/]*|clay)\.h"\s*$', '',code,flags=re.M)
        if name == "cui_dock" and source.startswith("src/components/"):
            lines += ['#if !defined(CUI_DOCK_BASE_ONLY)', f'/* {source} */', code, '#endif']
        else:
            lines += [f'/* {source} */',code]
    lines += ['#endif','']
    return '\n'.join(lines)
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    failed=False;output=ROOT/'dist';output.mkdir(exist_ok=True)
    for name,sources in MODULES.items():
        if not (ROOT/'include/cui'/(name+'.h')).exists():continue
        assert all((ROOT/p).exists() for p in sources),sources
        contents=generate(name,sources);target=output/(name+'.h')
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8")!=contents:
                print(f'{target.relative_to(ROOT)} is stale');failed=True
        else:target.write_text(contents, encoding="utf-8", newline="\n")
    for name in ['cui_renderer.h','cui_platform.h']:
        target=output/name;contents=(ROOT/'include/cui'/name).read_text(encoding="utf-8")
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8")!=contents:failed=True
        else:target.write_text(contents, encoding="utf-8", newline="\n")
    # Optional native adapters and Rust regex remain separately linked libraries.
    modules = [name for name, sources in MODULES.items() if sources]
    lines = ['/* Generated by scripts/amalgamate.py; DO NOT EDIT. */',
             '#ifndef CUI_ALL_H', '#define CUI_ALL_H']
    lines += [f'#include "{name}.h"' for name in modules]
    lines += ['#endif', '#if defined(CUI_IMPLEMENTATION_ALL) && !defined(CUI_IMPLEMENTATION_ALL_ONCE)',
              '#define CUI_IMPLEMENTATION_ALL_ONCE']
    for name in modules:
        lines += [f'#ifndef {name.upper()}_IMPLEMENTATION', f'#define {name.upper()}_IMPLEMENTATION',
                  '#endif', f'#include "{name}.h"']
    lines += ['#endif', '']
    generated = {'cui_all.h': '\n'.join(lines),
                 'implementations.json': json.dumps({
                     'scope': 'Portable C implementations; native adapters and Rust regex link separately.',
                     'umbrella': 'CUI_IMPLEMENTATION_ALL',
                     'modules': [{'header': name + '.h', 'macro': name.upper() + '_IMPLEMENTATION',
                                  'sources': MODULES[name]} for name in modules]}, indent=2) + '\n'}
    for name, contents in generated.items():
        target = output / name
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != contents:
                print(f'{target.relative_to(ROOT)} is stale');failed=True
        else:
            target.write_text(contents, encoding='utf-8', newline='\n')
    raise SystemExit(1 if failed else 0)
if __name__=='__main__':main()
