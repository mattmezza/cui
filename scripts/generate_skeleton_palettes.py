#!/usr/bin/env python3
"""Generate encoded Skeleton source tokens; no theme identity inference."""
import argparse
import hashlib
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
PIN = '03de5a483daab83ed983495963a560d70f8ea7db3fd079bf4a69a4df0e2f77c0'


def generate():
    data = (ROOT / 'third_party/gpui_themes/palettes.json').read_bytes()
    if hashlib.sha256(data).hexdigest() != PIN:
        raise ValueError('Pinned source changed: review Skeleton schema and independent oracle')
    source = json.loads(data)
    ordered = sorted(source['themes'], key=lambda t: (t['mode'] != 'light',
                     not t['name'].startswith('Default '), t['name'].casefold()))
    expected = json.loads((ROOT / 'third_party/gpui_themes/presets.json').read_text())
    if [(t['name'], t['mode']) for t in ordered] != [(t['name'], t['mode']) for t in expected]:
        raise ValueError('Preset order differs from canonical registry')
    lines = ['/* Generated by scripts/generate_skeleton_palettes.py; DO NOT EDIT. */',
             'static const cui_skeleton_palette cui_skeleton_palette_records[] = {']
    for theme in ordered:
        colors = theme['colors']
        value = (colors['skeleton.background'] if 'skeleton.background' in colors
                 else colors['secondary.background'])
        value = source['named_colors'].get(value, value)
        if not re.fullmatch(r'#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?', value):
            raise ValueError('Unsupported Skeleton source color: ' + value)
        channels = bytes.fromhex(value[1:] + ('ff' if len(value) == 7 else ''))
        lines.append('    {{' + ', '.join(map(str, channels)) + '}}, /* ' + theme['name'] + ' */')
    return '\n'.join(lines + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/theme/cui_skeleton_palette_presets.inc'
    data = generate().encode()
    if args.check:
        if not target.is_file() or target.read_bytes() != data:
            raise SystemExit('Stale Skeleton palettes; run scripts/generate_skeleton_palettes.py')
    elif not target.is_file() or target.read_bytes() != data:
        target.write_bytes(data)


if __name__ == '__main__':
    main()
