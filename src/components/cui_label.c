typedef struct {
    uint32_t scalar;
    size_t start, end;
} label_scalar;
static bool decode(cui_str s, label_scalar *out, size_t *count) {
    size_t n = 0, i = 0;
    if (s.length && !s.data)
        return false;
    while (i < s.length) {
        size_t start = i;
        unsigned char b = (unsigned char)s.data[i++];
        uint32_t cp;
        size_t extra;
        if (b < 0x80) {
            cp = b;
            extra = 0;
        } else if (b >= 0xc2 && b <= 0xdf) {
            cp = b & 31u;
            extra = 1;
        } else if (b >= 0xe0 && b <= 0xef) {
            cp = b & 15u;
            extra = 2;
        } else if (b >= 0xf0 && b <= 0xf4) {
            cp = b & 7u;
            extra = 3;
        } else
            return false;
        if (extra > s.length - i)
            return false;
        for (size_t j = 0; j < extra; ++j) {
            unsigned char c = (unsigned char)s.data[i++];
            if ((c & 0xc0u) != 0x80u)
                return false;
            cp = (cp << 6) | (c & 63u);
        }
        if ((extra == 1 && cp < 0x80) || (extra == 2 && cp < 0x800) ||
            (extra == 3 && cp < 0x10000) || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff))
            return false;
        if (out)
            out[n] = (label_scalar){cp, start, i};
        ++n;
    }
    *count = n;
    return true;
}
static bool property(uint32_t cp, const scalar_range *ranges, size_t n) {
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < ranges[mid].first)
            hi = mid;
        else if (cp > ranges[mid].last)
            lo = mid + 1;
        else
            return true;
    }
    return false;
}
#define PROP(cp, p) property(cp, p, sizeof(p) / sizeof(p[0]))
static bool final_sigma(const label_scalar *s, size_t n, size_t i) {
    bool before = false;
    for (size_t j = i; j > 0;) {
        uint32_t cp = s[--j].scalar;
        if (PROP(cp, case_ignorable))
            continue;
        before = PROP(cp, cased);
        break;
    }
    if (!before)
        return false;
    for (size_t j = i + 1; j < n; ++j) {
        if (PROP(s[j].scalar, case_ignorable))
            continue;
        return !PROP(s[j].scalar, cased);
    }
    return true;
}
static size_t lowercase(const label_scalar *s, size_t n, label_scalar *out) {
    size_t count = 0;
    for (size_t i = 0; i < n; ++i) {
        uint32_t first = s[i].scalar, second = 0;
        size_t lo = 0, hi = sizeof(lower_table) / sizeof(lower_table[0]);
        while (lo < hi) {
            size_t mid = lo + (hi - lo) / 2;
            if (lower_table[mid].scalar < first)
                lo = mid + 1;
            else
                hi = mid;
        }
        if (lo < sizeof(lower_table) / sizeof(lower_table[0]) && lower_table[lo].scalar == first) {
            first = lower_table[lo].first;
            second = lower_table[lo].second;
        }
        if (s[i].scalar == 0x3a3 && final_sigma(s, n, i))
            first = 0x3c2;
        out[count++] = (label_scalar){first, s[i].start, s[i].end};
        if (second)
            out[count++] = (label_scalar){second, s[i].start, s[i].end};
    }
    return count;
}
static bool same_color(cui_color a, cui_color b) {
    return a.r == b.r && a.g == b.g && a.b == b.b && a.a == b.a;
}
bool cui_label_prepare(const cui_theme *theme, cui_label_options o, char *text, size_t capacity,
                       cui_text_color_span *spans, size_t span_capacity,
                       cui_label_prepared *result) {
    size_t pn = 0, sn = 0, hn = 0;
    if (o.alignment < CUI_TEXT_ALIGN_LEFT || o.alignment > CUI_TEXT_ALIGN_RIGHT || !theme ||
        !result || o.match > CUI_LABEL_MATCH_PREFIX || o.match < CUI_LABEL_MATCH_FULL ||
        !isfinite(o.font_size) || o.font_size < 0 || !isfinite(o.line_height) ||
        o.line_height < 0 || o.style.weight > CUI_TEXT_WEIGHT_BOLD ||
        o.style.weight < CUI_TEXT_WEIGHT_NORMAL || !decode(o.primary, NULL, &pn) ||
        !decode(o.secondary, NULL, &sn) || !decode(o.highlight, NULL, &hn))
        return false;
    size_t sep = o.has_secondary ? 1u : 0u;
    if (o.primary.length > SIZE_MAX - sep ||
        (o.has_secondary && o.secondary.length > SIZE_MAX - o.primary.length - sep))
        return false;
    size_t length = o.primary.length + sep + (o.has_secondary ? o.secondary.length : 0);
    if (length > SIZE_MAX / sizeof(label_scalar) / 2 - 1 ||
        hn > SIZE_MAX / sizeof(label_scalar) / 2 - 1)
        return false;
    size_t scalars = pn + sep + (o.has_secondary ? sn : 0);
    if (o.masked) {
        if (scalars > SIZE_MAX / 3 || scalars * 3 > capacity || (scalars && !text))
            return false;
        for (size_t i = 0; i < scalars; ++i)
            memcpy(text + i * 3, "\xe2\x80\xa2", 3);
        *result = (cui_label_prepared){scalars * 3, 0};
        return true;
    }
    if (length > capacity || (length && !text))
        return false;
    char *joined = malloc(length + 1);
    label_scalar *original = malloc((length + 1) * sizeof(*original));
    label_scalar *lower = malloc((length + 1) * 2 * sizeof(*lower));
    label_scalar *needle = malloc((hn + 1) * sizeof(*needle));
    label_scalar *needle_lower = malloc((hn + 1) * 2 * sizeof(*needle_lower));
    unsigned char *marked = calloc(length + 1, 1);
    cui_text_color_span *colors = malloc((scalars + 1) * sizeof(*colors));
    bool ok = false;
    if (!joined || !original || !lower || !needle || !needle_lower || !marked || !colors)
        goto done;
    if (o.primary.length)
        memcpy(joined, o.primary.data, o.primary.length);
    if (sep)
        joined[o.primary.length] = ' ';
    if (o.has_secondary && o.secondary.length)
        memcpy(joined + o.primary.length + 1, o.secondary.data, o.secondary.length);
    (void)decode((cui_str){joined, length}, original, &scalars);
    (void)decode(o.highlight, needle, &hn);
    size_t ln = lowercase(original, scalars, lower), nn = lowercase(needle, hn, needle_lower);
    if (nn && nn <= ln)
        for (size_t i = 0; i <= ln - nn; ++i) {
            if (o.match == CUI_LABEL_MATCH_PREFIX && i > 0)
                break;
            size_t j = 0;
            while (j < nn && lower[i + j].scalar == needle_lower[j].scalar)
                ++j;
            if (j == nn)
                for (size_t b = lower[i].start; b < lower[i + nn - 1].end; ++b)
                    marked[b] = 1;
        }
    size_t cn = 0;
    cui_color base = o.custom_color ? o.color : theme->text;
    for (size_t i = 0; i < scalars; ++i) {
        size_t start = original[i].start, end = original[i].end;
        cui_color color =
            marked[start] ? theme->info
                          : (o.has_secondary && start >= o.primary.length ? theme->muted : base);
        if (cn && same_color(colors[cn - 1].color, color))
            colors[cn - 1].byte_end = end;
        else
            colors[cn++] = (cui_text_color_span){start, end, color};
    }
    if (cn > span_capacity || cn > CUI_TEXT_COLOR_SPAN_MAX || (cn && !spans))
        goto done;
    if (length)
        memcpy(text, joined, length);
    if (cn)
        memcpy(spans, colors, cn * sizeof(*spans));
    *result = (cui_label_prepared){length, cn};
    ok = true;
done:
    free(joined);
    free(original);
    free(lower);
    free(needle);
    free(needle_lower);
    free(marked);
    free(colors);
    return ok;
}
bool cui_label_source(cui_context *ui, const cui_theme *theme, cui_label_options o) {
    if (!ui || !theme || o.primary.length > SIZE_MAX / 3 - 1 ||
        o.secondary.length > SIZE_MAX / 3 - 1 - o.primary.length)
        return false;
    size_t capacity = (o.primary.length + o.secondary.length + 1) * 3;
    char *text = malloc(capacity);
    cui_text_color_span *spans = malloc(CUI_TEXT_COLOR_SPAN_MAX * sizeof(*spans));
    cui_label_prepared prepared;
    bool ok = false;
    if (!text || !spans ||
        !cui_label_prepare(theme, o, text, capacity, spans, CUI_TEXT_COLOR_SPAN_MAX, &prepared))
        goto done;
    cui_str display = {text, prepared.text_length};
    float font = o.font_size ? o.font_size : theme->font_size;
    if (!isfinite(font) || font <= 0)
        goto done;
    if (o.semantic_id)
        cui_begin_box(ui, o.semantic_id,
                      (cui_box){.width = o.alignment == CUI_TEXT_ALIGN_LEFT ? 0 : -1});
    if (o.alignment == CUI_TEXT_ALIGN_LEFT)
        ok = cui_text_paragraph_colored(ui, display, font, o.custom_color ? o.color : theme->text,
                                        o.line_height ? o.line_height : 20, o.style, !o.no_wrap,
                                        spans, prepared.span_count);
    else
        ok = cui_text_paragraph_colored_aligned(
            ui, display, font, o.custom_color ? o.color : theme->text,
            o.line_height ? o.line_height : 20, o.style, !o.no_wrap, spans, prepared.span_count,
            o.alignment);
    if (ok && o.semantic_id) {
        (void)cui_interact(ui, o.semantic_id, CUI_ROLE_LABEL, display, false, false, 0);
        cui_set_semantic_details(ui, o.semantic_id,
                                 (cui_semantic_details){.controls = o.control,
                                                        .focus_target = o.control,
                                                        .secret = o.masked});
    }
    if (o.semantic_id)
        cui_end_box(ui);
done:
    free(text);
    free(spans);
    return ok;
}
