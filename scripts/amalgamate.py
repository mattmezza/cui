#!/usr/bin/env python3
"""Reproduce standalone distribution headers; no network/toolchain required."""
import argparse,difflib,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
MODULES={"cui_resizable": ["src/base/cui_resizable.c", "src/components/cui_resizable.c"], "cui_chrome": ["src/base/cui_chrome.c", "src/components/cui_chrome.c"], "cui_description": ["src/base/cui_description.c", "src/components/cui_description.c"], "cui_media": ["src/base/cui_media.c", "src/components/cui_media.c"], "cui_message": ["src/base/cui_message.c", "src/components/cui_message.c"], "cui_status": ["src/base/cui_status.c", "src/components/cui_status.c"], "cui_otp": ["src/base/cui_otp.c", "src/components/cui_otp.c"], "cui_form": ["src/base/cui_form.c", "src/components/cui_form.c"], "cui_surface": ["src/base/cui_surface.c", "src/components/cui_surface.c"], "cui_table": ["src/base/cui_table.c", "src/components/cui_table.c"], "cui_scroll": ["src/base/cui_scroll.c", "src/components/cui_scroll.c"], "cui_tree": ["src/base/cui_tree.c", "src/components/cui_tree.c"], "cui_picker": ["src/base/cui_picker.c", "src/components/cui_picker.c"], "cui_numeric": ["src/base/cui_numeric.c", "src/components/cui_numeric.c"], "cui_content": ["src/base/cui_content.c", "src/components/cui_content.c"], "cui_disclosure": ["src/base/cui_disclosure.c", "src/components/cui_disclosure.c"], "cui_choice": ["src/base/cui_choice.c", "src/components/cui_choice.c"], "cui_plot": ["src/base/cui_plot.c"],"cui": ["src/core/cui.c"],"cui_dock": ["src/base/cui_dock.c"],"cui_virtual": ["src/base/cui_virtual.c"],"cui_overlay": ["src/base/cui_overlay.c"],"cui_edit": ["src/base/cui_edit.c"],"cui_base": ["src/base/cui_base.c","src/base/cui_models.c"],"cui_theme": ["src/theme/cui_theme.c"],"cui_components": ["src/components/cui_components.c"]}
def generate(name,sources):
    declaration=(ROOT/"include/cui"/(name+".h")).read_text(encoding="utf-8")
    declaration=re.sub(r'#include "cui/([^"\n]+)"',r'#include "\1"',declaration)
    lines=['/* Generated by scripts/amalgamate.py; DO NOT EDIT. SPDX-License-Identifier: MIT */',declaration]
    macro=name.upper()+"_IMPLEMENTATION"
    lines += [f'#if defined({macro}) && !defined({macro}_ONCE)',f'#define {macro}_ONCE']
    if name in {"cui_choice", "cui_surface", "cui_form", "cui_status", "cui_message"}:
        lines += ['#include "cui_components.h"']
    if name=="cui_base":
        lines += ['#ifndef CUI_EDIT_IMPLEMENTATION','#define CUI_EDIT_IMPLEMENTATION','#endif','#include "cui_edit.h"']
    if name=="cui_components":
        lines += ['#ifndef CUI_THEME_IMPLEMENTATION','#define CUI_THEME_IMPLEMENTATION','#endif','#include "cui_theme.h"']
    if name=="cui_components":
        for module in ["cui_content", "cui_disclosure", "cui_choice", "cui_numeric", "cui_picker", "cui_tree", "cui_table", "cui_scroll", "cui_surface", "cui_form", "cui_otp", "cui_status", "cui_message", "cui_media", "cui_description", "cui_chrome", "cui_resizable"]:
            macro_dependency = module.upper()+"_IMPLEMENTATION"
            lines += [f'#ifndef {macro_dependency}',f'#define {macro_dependency}', '#endif',f'#include "{module}.h"']
    for source in sources:
        code=(ROOT/source).read_text(encoding="utf-8")
        if name=='cui':
            code=code.replace('#include "clay.h"',(ROOT/'third_party/clay/clay.h').read_text(encoding="utf-8"))
        code=re.sub(r'^#include "(?:cui/)?(?:cui[^"/]*|clay)\.h"\s*$', '',code,flags=re.M)
        lines += [f'/* {source} */',code]
    lines += ['#endif','']
    return '\n'.join(lines)
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    failed=False;output=ROOT/'dist';output.mkdir(exist_ok=True)
    for name,sources in MODULES.items():
        if not (ROOT/'include/cui'/(name+'.h')).exists():continue
        assert all((ROOT/p).exists() for p in sources),sources
        contents=generate(name,sources);target=output/(name+'.h')
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8")!=contents:
                print(f'{target.relative_to(ROOT)} is stale');failed=True
        else:target.write_text(contents, encoding="utf-8", newline="\n")
    for name in ['cui_renderer.h','cui_platform.h']:
        target=output/name;contents=(ROOT/'include/cui'/name).read_text(encoding="utf-8")
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8")!=contents:failed=True
        else:target.write_text(contents, encoding="utf-8", newline="\n")
    raise SystemExit(1 if failed else 0)
if __name__=='__main__':main()
