#!/usr/bin/env python3
"""Compile original GLSL to pinned checked-in SPIR-V byte arrays (optional tool)."""
import argparse,subprocess,tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
parts=['/* Generated by scripts/gpu_shaders.py from original MIT GLSL. */']
with tempfile.TemporaryDirectory() as d:
 for source in ['ui.vert','ui.frag','mesh.vert','mesh.frag']:
  stage=source.rsplit('.',1)[1]
  dest=Path(d)/(source+'.spv')
  subprocess.run(['glslc','--target-env=vulkan1.0',str(root/'backends/sdl_gpu/shaders'/source),'-o',str(dest)],check=True)
  data=dest.read_bytes();parts.append('static const unsigned char cui_gpu_'+('mesh_' if source.startswith('mesh.') else '')+stage+'[] = {')
  for i in range(0,len(data),16):parts.append('    '+','.join(str(x) for x in data[i:i+16])+',')
  parts.append('};')
contents='\n'.join(parts)+'\n';path=root/'backends/sdl_gpu/shaders/generated.h'
if a.check:raise SystemExit(contents!=path.read_text(encoding="utf-8"))
path.write_text(contents, encoding="utf-8", newline="\n")
