#!/usr/bin/env python3
"""Generate the Command matcher's Unicode tables from pinned, offline data."""
import argparse
from hashlib import sha256
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "third_party/unicode/17.0.0"
OUTPUT = ROOT / "src/base/cui_command_unicode.inc"


def records(source):
    for row in source.splitlines():
        data = row.partition("#")[0].strip()
        if data:
            yield [field.strip() for field in data.split(";")]


def lowercase_ranges(codepoints):
    """Coalesce same-delta runs, including alternating uppercase/lowercase pairs."""
    i = 0
    while i < len(codepoints):
        start, delta = codepoints[i]
        end, step = start, 1
        i += 1
        if i < len(codepoints) and codepoints[i][1] == delta:
            step = min(2, codepoints[i][0] - start)
        while i < len(codepoints) and codepoints[i] == (end + step, delta):
            end += step
            i += 1
        yield f"    {{0x{start:X}, 0x{end:X}, {delta}, {step}}},"


def generate():
    manifest = json.loads((DATA / "manifest.json").read_text(encoding="utf-8"))
    if manifest["unicode_version"] != DATA.name:
        raise ValueError("Unicode manifest version does not match the data directory")
    inputs = {}
    for name in ("UnicodeData.txt", "SpecialCasing.txt", "DerivedCoreProperties.txt", "PropList.txt"):
        source = (DATA / name).read_bytes()
        if sha256(source).hexdigest() != manifest["files"][name]["sha256"]:
            raise ValueError(f"{name} differs from the pinned Unicode data")
        inputs[name] = source.decode()

    mapping = {int(row[0], 16): (int(row[13], 16),)
               for row in records(inputs["UnicodeData.txt"]) if row[13]}
    expanded, contextual = {}, {}
    for code, lower, _, _, conditions, *_ in records(inputs["SpecialCasing.txt"]):
        scalar = int(code, 16)
        replacement = tuple(int(cp, 16) for cp in lower.split())
        if not conditions:
            mapping[scalar] = replacement
            if len(replacement) > 1:
                expanded[scalar] = replacement
        elif not {"lt", "tr", "az"}.intersection(conditions.split()):
            contextual[(scalar, conditions)] = replacement
    if expanded != {0x130: (0x69, 0x307)} or contextual != {(0x3A3, "Final_Sigma"): (0x3C2,)}:
        raise ValueError("Update the Command matcher for new default special casing rules")
    lowercase = sorted((cp, lower[0] - cp) for cp, lower in mapping.items()
                       if cp >= 128 and len(lower) == 1 and lower[0] != cp)

    flags = bytearray(0x110000)
    properties = {"Cased": 1, "Case_Ignorable": 2, "White_Space": 4}
    for name in ("DerivedCoreProperties.txt", "PropList.txt"):
        for bounds, prop, *_ in records(inputs[name]):
            if prop in properties:
                ends = bounds.split("..")
                for cp in range(int(ends[0], 16), int(ends[-1], 16) + 1):
                    flags[cp] |= properties[prop]
    runs = []
    start = 128
    for cp in range(start + 1, len(flags) + 1):
        if cp == len(flags) or flags[cp] != flags[start]:
            if flags[start]:
                runs.append(f"    {{0x{start:X}, 0x{cp - 1:X}, {flags[start]}}},")
            start = cp

    return "\n".join([
        "/* Generated by scripts/generate_command_unicode.py. Unicode 17.0.0, Unicode License V3. */",
        "static const unsigned char cui_command_ascii_properties[128] = {",
        *(f"    [{cp}] = {flag}," for cp, flag in enumerate(flags[:128]) if flag),
        "};",
        "static const struct { uint32_t first, last; unsigned char flags; }",
        "cui_command_properties[] = {", *runs, "};",
        "static const struct { uint32_t first, last; int32_t delta; unsigned char step; }",
        "cui_command_lowercase[] = {", *lowercase_ranges(lowercase), "};", "",
    ]).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if OUTPUT.is_file() and OUTPUT.read_bytes() == output:
        return
    if args.check:
        raise SystemExit(f"{OUTPUT}: regenerate with {__file__}")
    OUTPUT.write_bytes(output)


if __name__ == "__main__":
    main()
