#!/usr/bin/env python3
"""Generate the pinned icon catalog and optional SVG bundles without network access."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    archive = json.loads((ROOT / "third_party/gpui_icons/icons.json").read_text())
    names = sorted(archive["icons"])
    defaults = set(archive["default_names"])
    # Application essentials from the same pinned archive; never fetch assets.
    defaults.update({"pencil", "pen-line", "funnel", "archive", "trash", "mail",
                     "mail-open", "paperclip", "send", "reply", "reply-all", "forward",
                     "download", "upload", "link", "log-out", "check-check"})
    missing = defaults.difference(names)
    if missing:
        raise ValueError(f"Unknown default icons: {sorted(missing)}")
    license_text = (ROOT / "third_party/gpui_icons/LICENSE").read_text().replace("*/", "* /")
    output = ["/* Generated by scripts/icon_assets.py; do not edit.", license_text, "*/"]
    for i, name in enumerate(names):
        if name not in defaults:
            output.append("#if defined(CUI_ICON_ALL_ASSETS) && CUI_ICON_ALL_ASSETS")
        output.append(f"static const char cui_icon_svg_{i}[] = " + json.dumps(archive["icons"][name]) + ";")
        if name not in defaults:
            output.extend(["#else", f"#define cui_icon_svg_{i} NULL", "#endif"])
    output.append("static const cui_icon_asset_record cui_icon_assets[] = {")
    for i, name in enumerate(names):
        output.append("    {" + json.dumps(name) + ", " + json.dumps("icons/" + name + ".svg") +
                      f", cui_icon_svg_{i}, " + ("true" if name in defaults else "false") + "},")
    output.append("};\n")
    return "\n".join(output)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "src/base/cui_icon_assets.inc"
    content = generate()
    if args.check:
        if not destination.exists() or destination.read_text() != content:
            raise SystemExit("src/base/cui_icon_assets.inc is stale")
    else:
        destination.write_text(content, newline="\n")

if __name__ == "__main__":
    main()
