#!/usr/bin/env python3
"""Generate source-specific owned Slider palettes; never flatten thumb brushes."""
import argparse
import hashlib
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
PIN = '03de5a483daab83ed983495963a560d70f8ea7db3fd079bf4a69a4df0e2f77c0'


def generate():
    data = (ROOT / 'third_party/gpui_themes/palettes.json').read_bytes()
    if hashlib.sha256(data).hexdigest() != PIN:
        raise ValueError('Pinned source changed; review Slider token/oracle semantics before refreshing')
    source = json.loads(data)
    def color(value):
        value = source['named_colors'].get(value, value)
        match = re.fullmatch(r'#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?', value)
        if not match:
            raise ValueError('Unsupported source Slider color: ' + value)
        channels = bytes.fromhex(match[1] + (match[2] or 'ff'))
        # Source theme hex -> HSLA -> pinned shader RGB is the same mathematical
        # channel fraction, treated as LINEAR by that shader; no sRGB decode.
        return '{' + ', '.join(format(c / 255, '.9f') + 'f' for c in channels) + '}'
    ordered = sorted(source['themes'], key=lambda t: (t['mode'] != 'light',
                     not t['name'].startswith('Default '), t['name'].casefold()))
    expected = json.loads((ROOT / 'third_party/gpui_themes/presets.json').read_text())
    if [(t['name'], t['mode']) for t in ordered] != [(t['name'], t['mode']) for t in expected]:
        raise ValueError('Named preset ordering differs from canonical CUI preset ordering')
    lines = ['/* Generated by scripts/generate_slider_palettes.py; DO NOT EDIT. */',
             'static const cui_slider_palette_record cui_slider_palette_records[] = {']
    for theme in ordered:
        raw = theme['colors']
        # Required fallback tokens are explicit in all pinned presets. No adapted
        # theme byte fallback or undocumented slider.bar.background alias.
        primary, foreground, blue = (raw[k] for k in ('primary.background', 'primary.foreground', 'base.blue'))
        bar = raw.get('slider.background', primary)
        if bar.startswith('linear-gradient('):
            bar = re.fullmatch(r'linear-gradient\([^,]+,\s*([^,]+),[^)]+\)', bar)[1]
        thumb = raw.get('slider.thumb.background', foreground)
        ring = raw.get('ring', blue)
        if thumb.startswith('linear-gradient('):
            match = re.fullmatch(r'linear-gradient\(180deg,\s*(#[0-9a-fA-F]{6}),\s*(#[0-9a-fA-F]{6})\)', thumb)
            if not match:
                raise ValueError('Unreviewed Slider brush syntax: ' + thumb)
            brush = '{.kind = CUI_SLIDER_BRUSH_LINEAR, .space = CUI_SLIDER_BRUSH_SRGB, ' \
                    '.projection = CUI_SLIDER_BRUSH_SOURCE_038, .angle_degrees = 180, .stops = ' \
                    '{{0, ' + color(match[1]) + '}, {1, ' + color(match[2]) + '}}}'
        else:
            brush = '{.kind = CUI_SLIDER_BRUSH_SOLID, .solid = ' + color(thumb) + '}'
        lines.append('    {' + json.dumps(theme['name']) + ', {.bar = ' + color(bar) +
                     ', .ring = ' + color(ring) + ', .thumb = ' + brush + '}},')
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    target = ROOT / 'src/theme/cui_slider_palette_presets.inc'
    if args.check:
        if not target.is_file() or target.read_text() != content:
            raise SystemExit('Stale Slider palettes; run scripts/generate_slider_palettes.py')
    else:
        target.write_text(content)


if __name__ == '__main__': main()
