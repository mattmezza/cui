#!/usr/bin/env python3
"""Generate portable Unicode 17 EGC properties/tests from checked-in pinned data."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'third_party/unicode/17.0.0'
BEGIN = '/* BEGIN GENERATED UNICODE GRAPHEME TABLE */'
END = '/* END GENERATED UNICODE GRAPHEME TABLE */'
PROPS = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
         'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']


def generate():
    manifest = json.loads((DATA / 'manifest.json').read_text())
    for name, record in manifest['files'].items():
        assert hashlib.sha256((DATA / name).read_bytes()).hexdigest() == record['sha256'], name
    flags = [0] * 0x110000
    for name, kind in [('GraphemeBreakProperty.txt', 'gcb'), ('emoji-data.txt', 'ep'),
                       ('DerivedCoreProperties.txt', 'incb')]:
        for line in (DATA / name).read_text().splitlines():
            fields = [x.strip() for x in line.split('#')[0].split(';')]
            if len(fields) < 2 or not fields[0]:
                continue
            if kind == 'gcb':
                value = PROPS.index(fields[1])
            elif kind == 'ep':
                if fields[1] != 'Extended_Pictographic':
                    continue
                value = 16
            else:
                if len(fields) < 3 or fields[1] != 'InCB':
                    continue
                value = {'Consonant': 32, 'Extend': 64, 'Linker': 96}[fields[2]]
            bounds = fields[0].split('..')
            lo, hi = int(bounds[0], 16), int(bounds[-1], 16)
            for cp in range(lo, hi + 1):
                flags[cp] |= value
    rows = []
    start = 0
    for cp in range(1, len(flags) + 1):
        if cp == len(flags) or flags[cp] != flags[start]:
            if flags[start]:
                rows.append(f'    {{0x{start:X}, 0x{cp-1:X}, {flags[start]}}},')
            start = cp
    table = BEGIN + '\n// clang-format off\n/* Unicode 17.0.0; Unicode License V3, see third_party/unicode/17.0.0. */\n'
    table += 'static const struct { uint32_t first, last; unsigned char flags; }\n'
    table += 'cui_edit_private_grapheme_ranges[] = {\n' + '\n'.join(rows) + '\n};\n// clang-format on\n' + END
    cases = []
    for line in (DATA / 'GraphemeBreakTest.txt').read_text().splitlines():
        words = line.split('#')[0].split()
        if not words:
            continue
        data = bytearray()
        boundaries = []
        for word in words:
            if word == '÷':
                boundaries.append(len(data))
            elif word != '×':
                data.extend(chr(int(word, 16)).encode())
        encoded = ''.join(f'\\x{x:02x}' for x in data)
        cases.append(f'    {{"{encoded}", {len(data)}, {len(boundaries)}, '
                     + '{' + ', '.join(map(str, boundaries)) + '}},')
    fixture = '/* Generated by scripts/generate_grapheme.py; Unicode 17.0.0 License V3. */\n'
    fixture += 'static const struct { const char *text; size_t length, count; size_t offsets[32]; }\n'
    fixture += 'grapheme_cases[] = {\n' + '\n'.join(cases) + '\n};\n'
    return table, fixture


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    table, fixture = generate()
    path = ROOT / 'src/base/cui_edit.c'
    source = path.read_text()
    if BEGIN in source:
        source = source[:source.index(BEGIN)] + table + source[source.index(END) + len(END):]
    else:
        source = source.replace('typedef struct {', table + '\n\ntypedef struct {', 1)
    outputs = [(path, source), (ROOT / 'tests/unit/cui_edit_grapheme_tests.inc', fixture)]
    for path, output in outputs:
        if args.check:
            assert path.read_text() == output, f'{path}: regenerate with {__file__}'
        else:
            path.write_text(output)


if __name__ == '__main__':
    main()
