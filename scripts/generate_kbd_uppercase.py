#!/usr/bin/env python3
"""Generate the Kbd first-scalar uppercase table and test inputs offline."""
import argparse
from hashlib import sha256
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "third_party/unicode/17.0.0"
BEGIN = "/* BEGIN GENERATED KBD UPPERCASE TABLE */"
END = "/* END GENERATED KBD UPPERCASE TABLE */"


def uppercase_mappings():
    manifest = json.loads((DATA / "manifest.json").read_text(encoding="utf-8"))
    if manifest["unicode_version"] != DATA.name:
        raise ValueError("Unicode manifest version does not match the data directory")
    inputs = {}
    for name in ("UnicodeData.txt", "SpecialCasing.txt"):
        content = (DATA / name).read_bytes()
        if sha256(content).hexdigest() != manifest["files"][name]["sha256"]:
            raise ValueError(f"{name} differs from the pinned Unicode data")
        inputs[name] = content.decode().splitlines()

    mapping = {}
    for line in inputs["UnicodeData.txt"]:
        fields = line.split(";")
        if fields[12]:
            mapping[int(fields[0], 16)] = (int(fields[12], 16),)
    for line in inputs["SpecialCasing.txt"]:
        entry = line.partition("#")[0].strip()
        if not entry:
            continue
        code, _, _, upper, conditions, *_ = (field.strip() for field in entry.split(";"))
        if not conditions:
            mapping[int(code, 16)] = tuple(int(scalar, 16) for scalar in upper.split())
    return [
        (chr(code).encode(), "".join(chr(scalar) for scalar in upper).encode())
        for code, upper in sorted(mapping.items()) if upper != (code,)
    ]


def c_literal(data):
    return '"' + "".join(f"\\x{byte:02x}" for byte in data) + '"'


def generate():
    mappings = uppercase_mappings()
    maximum = max(len(upper) for _, upper in mappings)
    growth = max(len(upper) - len(key) for key, upper in mappings)
    table = [
        BEGIN,
        "// clang-format off",
        "/* Generated by scripts/generate_kbd_uppercase.py. Unicode 17.0.0, Unicode License V3. */",
        f"enum {{ CUI_KBD_UPPER_MAX_BYTES = {maximum}, CUI_KBD_UPPER_MAX_GROWTH = {growth} }};",
        "static const struct {",
        "    uint32_t key;",
        "    unsigned char length;",
        "    char upper[CUI_KBD_UPPER_MAX_BYTES + 1];",
        "} cui_kbd_uppercase_table[] = {",
    ]
    for key, upper in mappings:
        if len(key) > 1:  # ASCII uses the runtime fast path.
            table.append(f"    {{0x{int.from_bytes(key, 'big'):X}u, {len(upper)}, {c_literal(upper)}}},")
    table.extend(["};", "// clang-format on", END])

    fixture = [
        "/* Generated by scripts/generate_kbd_uppercase.py. Unicode 17.0.0, Unicode License V3. */",
        "static const struct { const char *key, *upper; } kbd_uppercase_cases[] = {",
    ]
    fixture.extend(f"    {{{c_literal(key)}, {c_literal(upper)}}}," for key, upper in mappings)
    fixture.extend(["};", ""])
    path = ROOT / "src/base/cui_kbd.c"
    source = path.read_text(encoding="utf-8")
    start, end = source.index(BEGIN), source.index(END) + len(END)
    return [(path, source[:start] + "\n".join(table) + source[end:]),
            (ROOT / "tests/unit/cui_kbd_uppercase_cases.inc", "\n".join(fixture))]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate():
        encoded = content.encode()
        if path.is_file() and path.read_bytes() == encoded:
            continue
        if args.check:
            raise SystemExit(f"{path}: regenerate with {__file__}")
        path.write_bytes(encoded)


if __name__ == "__main__":
    main()
